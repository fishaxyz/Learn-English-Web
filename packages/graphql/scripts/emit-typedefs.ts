// Bundles the .graphql files into one TypeScript module, so the API carries its schema with it
// (no file reads at runtime, works the same in tsx, vitest and the esbuild bundle).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSchema } from "graphql";

const dir = join(import.meta.dirname, "..", "schema");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".graphql"))
  .sort();
const sdl = files.map((f) => `# ${f}\n${readFileSync(join(dir, f), "utf8").trim()}\n`).join("\n");
buildSchema(sdl); // Fails loudly on an invalid schema.

const out = join(import.meta.dirname, "..", "src", "generated", "typedefs.ts");
writeFileSync(
  out,
  `// Generated by scripts/emit-typedefs.ts from schema/*.graphql. Do not edit.\nexport const typeDefs = ${JSON.stringify(sdl)};\n`
);
console.log(`typedefs: ${files.length} schema file(s)`);
